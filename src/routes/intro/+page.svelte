	<p>
		To put it into perspective, the playable characters in Hellsinker
		("EXECUTORs") are very, <i>very</i> different from each other.
		Functionally, each consists of a sizable moveset thanks to the game's
		3-button system which employs button combinations and tap speeds to do
		different attacks. Because of this, choosing a character is like picking
		and committing to a <b>fighting game</b> character. Newcomers
		<i>will</i> be stuck in between learning the "system mechanics" of Hellsinker
		and learning all of the options, tactics and strategies specific to their
		chosen EXECUTOR.
	</p>

