	<p>
		Despite that, practice will result in mastery of both, slowly resulting
		in less mistakes, optimization, and - where the game truly shines -
		aggressive, confident play. Trying to clear the game for the first time
		is a journey on its own that can take weeks, but once everything comes
		together, the game truly becomes as deep as the ocean. Levels become
		much more dynamic and hectic, reacting to your progress, while scoring
		becomes the encouraged, obvious goal - completely opposite of the
		defensive play that's required when starting out.
	</p>

