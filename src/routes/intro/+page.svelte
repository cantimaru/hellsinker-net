<h1>About Hellsinker</h1>
<hr />
<div class="paragraph">
	<p>
		<span class="standout">Hellsinker</span> is a bullet hell shoot-em-up ("shmup")
		video game, which involves lots of shooting at enemies while dodging dense,
		complex barrages of bullets. The story involves members of an organization
		who are launching their third attack on an ominous, great tower called the
		CARDINAL SHAFT, having to fight through onslaughts of "PRAYERs" birthed there.
		Going deeper, entering the trap, sinking into the hell that leads to HELLSINKER...
	</p>

