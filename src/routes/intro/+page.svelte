	<p>
		While shmups are plentiful nowadays and have been iterated upon,
		Hellsinker has had a long time's worth of praise and infamy. It sets
		itself apart from others in the genre in many ways, with difficulty
		ironically NOT being one of those ways. Rather, the complexity of its
		mechanics, and how much the game injects its setting directly into the
		gameplay - while mechanically and artistically inclined - is off-putting
		to those wanting to get on-board with the gameplay as soon as possible.
		Many couldn't stick with the game solely from the main menu and game UI,
		for that matter - and within Hellsinker, progress is very much a
		personal growth, arguably moreso than in other games. It accepts few
		transferable skills, has a notably lengthly run time, and the poetic
		chaos of its storytelling leaves many layers to unravel at a time. But
		if anything, Hellsinker's greatest faults lies in its age as a program
		and the (purposeful or not) sub-optimal default settings that come
		shipped with it.
	</p>

