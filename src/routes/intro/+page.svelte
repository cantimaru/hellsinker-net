	<p>
		If you're able to be patient and look past the superficial roadblocks,
		you'll be able to experience a carefully crafted and incredibly
		rewarding video game experience unlike anything that's out there. Past
		the immersive storytelling told through gameplay, a total of eight
		distinct shot types, three seperate scoring systems, high skill ceilings
		and player expression, this unassuming doujin game going 20 years old
		can truly offer so much for all sorts of players.
	</p>

	<p>
		There's much more that can be gushed about Hellsinker - whether it's the
		one-man development team with its history, the music that perfectly
		matches the themes of the game, the use of its graphics, and the
		incredibly obscure lore that has the potential to be a fountain of
		theories - this site was made as a tribute to all of it, and hopefully
		to allow other fans out there to connect on what we love about this fun
		little shmup!
